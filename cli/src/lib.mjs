/** Read a key from `.env` content. Returns undefined when it isn't set. */
export function getEnvVar(content, key) {
  const match = content.match(new RegExp(`^${key}=(.*)$`, "m"));
  return match ? match[1].trim() : undefined;
}

/** Set `key=value` in `.env` content, replacing the line or appending one. */
export function setEnvVar(content, key, value) {
  const line = `${key}=${value}`;
  const re = new RegExp(`^${key}=.*$`, "m");
  if (re.test(content)) return content.replace(re, () => line);
  return `${content}${content === "" || content.endsWith("\n") ? "" : "\n"}${line}\n`;
}

/** `"2.20.3"` / `"v2.40.0-desktop.1"` -> `[2, 20, 3]`. */
export function parseVersion(text) {
  const match = String(text).match(/(\d+)\.(\d+)(?:\.(\d+))?/);
  return match
    ? [Number(match[1]), Number(match[2]), Number(match[3] ?? 0)]
    : null;
}

export function versionAtLeast(actual, minimum) {
  const have = parseVersion(actual);
  const want = parseVersion(minimum);
  if (!have || !want) return false;
  for (let i = 0; i < 3; i++) {
    if (have[i] !== want[i]) return have[i] > want[i];
  }
  return true;
}

/** True when nothing is listening on `port` on this machine. */
export function isPortFree(port) {
  return new Promise((resolve) => {
    const server = net.createServer();
    server.once("error", () => resolve(false));
    server.once("listening", () => server.close(() => resolve(true)));
    server.listen(port);
  });
}

/** The first free port at or after `start`, or undefined if none in 100. */
export async function findFreePort(start) {
  for (let port = start; port < Math.min(start + 100, 65536); port++) {
    if (await isPortFree(port)) return port;
  }
  return undefined;
}

