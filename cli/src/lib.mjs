import { randomBytes } from "node:crypto";
import net from "node:net";

export const DEFAULT_REPO = "samata-oss/samata";
export const DEFAULT_REF = "main";
// Deliberately not 3000: that's the default for most dev servers (Next, Rails,
// Express...), so it's usually taken.
export const DEFAULT_PORT = 4747;
/** Ports the bundled LiveKit server publishes on the host. */
export const LIVEKIT_PORTS = [7880, 7881];
/** `name:` in the compose file. The CLI looks up its volumes by it. */
export const COMPOSE_PROJECT = "samata-local";

/** Where the local compose file lives in the repo. */
export function composeUrl({ repo = DEFAULT_REPO, ref = DEFAULT_REF } = {}) {
  return `https://raw.githubusercontent.com/${repo}/${ref}/deploy/docker-compose.local.yml`;
}

const secret = () => randomBytes(32).toString("hex");

/** A fresh `.env` for the local compose file, with newly generated secrets. */
export function generateEnv({ port = DEFAULT_PORT } = {}) {
  const lines = [
    "# Generated by `npx @samata-oss/cli init`. Keep this file: your database and the",
    "# provider keys stored in it can only be read with these secrets.",
    "",
    `POSTGRES_PASSWORD=${secret()}`,
    `SAMATA_WEBHOOK_SECRET=${secret()}`,
    `BETTER_AUTH_SECRET=${secret()}`,
    "LIVEKIT_API_KEY=samata",
    `LIVEKIT_API_SECRET=${secret()}`,
    "",
    "# Dashboard port on this machine.",
    `SAMATA_PORT=${port}`,
    "",
    "# Pin a release (e.g. 0.1.0) instead of tracking `latest`.",
    "# SAMATA_VERSION=latest",
    "# Pull the images from somewhere else (a fork).",
    "# SAMATA_IMAGE_PREFIX=ghcr.io/samata-oss",
    "",
  ];
  return lines.join("\n");
}

/** Read a key from `.env` content. Returns undefined when it isn't set. */
export function getEnvVar(content, key) {
  const match = content.match(new RegExp(`^${key}=(.*)$`, "m"));
  return match ? match[1].trim() : undefined;
}

/** Set `key=value` in `.env` content, replacing the line or appending one. */
export function setEnvVar(content, key, value) {
  const line = `${key}=${value}`;
  const re = new RegExp(`^${key}=.*$`, "m");
  if (re.test(content)) return content.replace(re, line);
  return `${content}${content === "" || content.endsWith("\n") ? "" : "\n"}${line}\n`;
}

/** `"2.20.3"` / `"v2.40.0-desktop.1"` -> `[2, 20, 3]`. */
export function parseVersion(text) {
  const match = String(text).match(/(\d+)\.(\d+)(?:\.(\d+))?/);
  return match
    ? [Number(match[1]), Number(match[2]), Number(match[3] ?? 0)]
    : null;
}

export function versionAtLeast(actual, minimum) {
  const have = parseVersion(actual);
  const want = parseVersion(minimum);
  if (!have || !want) return false;
  for (let i = 0; i < 3; i++) {
    if (have[i] !== want[i]) return have[i] > want[i];
  }
  return true;
}

/** True when nothing is listening on `port` on this machine. */
export function isPortFree(port) {
  return new Promise((resolve) => {
    const server = net.createServer();
    server.once("error", () => resolve(false));
    server.once("listening", () => server.close(() => resolve(true)));
    server.listen(port);
  });
}

/** The first free port at or after `start`, or undefined if none in 100. */
export async function findFreePort(start) {
  for (let port = start; port < Math.min(start + 100, 65536); port++) {
    if (await isPortFree(port)) return port;
  }
  return undefined;
}

/** A compose file we're willing to write to disk: it must look like one. */
export function looksLikeCompose(text) {
  return /^services:\s*$/m.test(text);
}
